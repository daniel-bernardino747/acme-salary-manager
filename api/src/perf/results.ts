import type { PerfRequest } from './requests';
import { meetsTarget, TARGET_MS, type Summary } from './summary';

/** What the results file says about the run itself (ADR 0006, *Write-up*). */
export interface RunInfo {
  /** When the run started, as an ISO 8601 UTC timestamp. */
  date: string;
  commit: string;
  baseUrl: string;
  region: string;
  seedMode: string;
  rowCount: number;
  clientLocation: string;
  warmUps: number;
  timed: number;
}

export interface EndpointResult {
  request: PerfRequest;
  server: Summary;
  client: Summary;
}

/** Milliseconds to two decimals: the precision of the `Server-Timing` header. */
const ms = (duration: number): string => duration.toFixed(2);

const figures = (summary: Summary): string[] =>
  [summary.cold, summary.p50, summary.p95, summary.max].map(ms);

const row = (cells: string[]): string => `| ${cells.join(' | ')} |`;

/** The run passes only when every endpoint meets the target (ADR 0006). */
function verdict(endpoints: readonly EndpointResult[]): string {
  const missed = endpoints.filter((endpoint) => !meetsTarget(endpoint.server));
  if (missed.length === 0) {
    return `**Result: pass.** The p95 server time is under ${TARGET_MS} ms on every endpoint.`;
  }
  const labels = missed.map((endpoint) => `"${endpoint.request.label}"`);
  const named =
    labels.length === 1
      ? labels.join('')
      : `${labels.slice(0, -1).join(', ')} and ${labels.at(-1)}`;
  return `**Result: fail.** The p95 server time is ${TARGET_MS} ms or more on ${named}.`;
}

/** `docs/performance-results.md`, generated and overwritten by each `pnpm perf` run (ADR 0006). */
export function renderResults(run: RunInfo, endpoints: readonly EndpointResult[]): string {
  return [
    '# Performance results',
    '',
    'Generated by `pnpm perf`; each run overwrites this file. What the figures mean, and how a cold',
    'run is done, is in [the performance note](performance.md).',
    '',
    verdict(endpoints),
    '',
    '| Run | |',
    row(['---', '---']),
    row(['Date (UTC)', run.date]),
    row(['Commit', `\`${run.commit}\``]),
    row(['Base URL', run.baseUrl]),
    row(['Railway region', run.region]),
    row(['Seed mode', run.seedMode]),
    row(['Employees', String(run.rowCount)]),
    row(['Client ran from', run.clientLocation]),
    '',
    'Times in milliseconds. Cold is the first request to the endpoint in the run. p50, p95 and max',
    `are over ${run.timed} sequential requests, after ${run.warmUps} warm-ups.`,
    '',
    row([
      'Endpoint',
      'Request',
      ...['cold', 'p50', 'p95', 'max'].map((figure) => `Server ${figure}`),
      ...['cold', 'p50', 'p95', 'max'].map((figure) => `Client ${figure}`),
      'Result',
    ]),
    row(['---', '---', ...Array<string>(8).fill('---:'), '---']),
    ...endpoints.map((endpoint) =>
      row([
        endpoint.request.label,
        `\`GET ${endpoint.request.path}\``,
        ...figures(endpoint.server),
        ...figures(endpoint.client),
        meetsTarget(endpoint.server) ? 'pass' : 'fail',
      ]),
    ),
    '',
  ].join('\n');
}
