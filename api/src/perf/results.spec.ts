import { describe, expect, it } from 'vitest';
import { renderResults, type RunInfo } from './results';

const run: RunInfo = {
  date: '2026-10-16T14:05:09.123Z',
  commit: '83c68a0',
  baseUrl: 'https://acme.example.app',
  region: 'europe-west4',
  seedMode: '--if-empty',
  rowCount: 10_000,
  clientLocation: 'a laptop in São Paulo, on home fibre',
  warmUps: 3,
  timed: 100,
};

describe('renderResults', () => {
  it('writes the run, then one row per endpoint, and passes when every p95 server time is under 500 ms', () => {
    const markdown = renderResults(run, [
      {
        request: { label: 'Employees, first page', path: '/api/employees' },
        server: { cold: 40.5, p50: 2.25, p95: 3, max: 9.75 },
        client: { cold: 912.333, p50: 180.1, p95: 201.457, max: 340 },
      },
      {
        request: { label: 'Payroll totals', path: '/api/payroll-totals' },
        server: { cold: 120, p50: 30.5, p95: 499.99, max: 612 },
        client: { cold: 1300, p50: 210, p95: 690.004, max: 820.5 },
      },
    ]);

    expect(markdown).toBe(
      [
        '# Performance results',
        '',
        'Generated by `pnpm perf`; each run overwrites this file. What the figures mean, and how a cold',
        'run is done, is in [the performance note](performance.md).',
        '',
        '**Result: pass.** The p95 server time is under 500 ms on every endpoint.',
        '',
        '| Run | |',
        '| --- | --- |',
        '| Date (UTC) | 2026-10-16T14:05:09.123Z |',
        '| Commit | `83c68a0` |',
        '| Base URL | https://acme.example.app |',
        '| Railway region | europe-west4 |',
        '| Seed mode | --if-empty |',
        '| Employees | 10000 |',
        '| Client ran from | a laptop in São Paulo, on home fibre |',
        '',
        'Times in milliseconds. Cold is the first request to the endpoint in the run. p50, p95 and max',
        'are over 100 sequential requests, after 3 warm-ups.',
        '',
        '| Endpoint | Request | Server cold | Server p50 | Server p95 | Server max | Client cold | Client p50 | Client p95 | Client max | Result |',
        '| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | --- |',
        '| Employees, first page | `GET /api/employees` | 40.50 | 2.25 | 3.00 | 9.75 | 912.33 | 180.10 | 201.46 | 340.00 | pass |',
        '| Payroll totals | `GET /api/payroll-totals` | 120.00 | 30.50 | 499.99 | 612.00 | 1300.00 | 210.00 | 690.00 | 820.50 | pass |',
        '',
      ].join('\n'),
    );
  });

  it('fails when any p95 server time reaches 500 ms, naming those endpoints', () => {
    const at = (p95: number) => ({ cold: 900, p50: 100, p95, max: 900 });
    const markdown = renderResults(run, [
      {
        request: { label: 'Payroll totals', path: '/api/payroll-totals' },
        server: at(500),
        client: at(600),
      },
      {
        request: { label: 'Outliers, all', path: '/api/outliers' },
        server: at(499.99),
        client: at(600),
      },
      {
        request: { label: 'Pay comparison', path: '/api/pay-comparison' },
        server: at(731.5),
        client: at(800),
      },
    ]);

    expect(markdown).toContain(
      '**Result: fail.** The p95 server time is 500 ms or more on Payroll totals and Pay comparison.',
    );
    expect(markdown).not.toContain('Result: pass');
    expect(markdown).toContain(
      [
        '| Payroll totals | `GET /api/payroll-totals` | 900.00 | 100.00 | 500.00 | 900.00 | 900.00 | 100.00 | 600.00 | 900.00 | fail |',
        '| Outliers, all | `GET /api/outliers` | 900.00 | 100.00 | 499.99 | 900.00 | 900.00 | 100.00 | 600.00 | 900.00 | pass |',
        '| Pay comparison | `GET /api/pay-comparison` | 900.00 | 100.00 | 731.50 | 900.00 | 900.00 | 100.00 | 800.00 | 900.00 | fail |',
      ].join('\n'),
    );
  });
});
